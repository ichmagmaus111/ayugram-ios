#!/bin/bash
# XTG: pin bazel to the Xcode that `xcode-select` points at.
#
# Bazel discovers Xcodes through LaunchServices (`tools/osx/xcode_locator.m` →
# LSCopyApplicationURLsForBundleIdentifier) and then looks for the `xcode-select`ed one
# in that list. On macOS 27 LaunchServices answers with the newest Xcode only, so with a
# beta installed next to the release Xcode bazel silently picks the beta (2026-09-10:
# "No default Xcode version is set with 'xcode-select'; picking ':version27_0_0_27A266a'").
# The damage: the Info.plist stamps (DTXcode, DTSDKName, DTPlatformVersion) say 27.0 and
# App Store Connect refuses a build made with a beta, every disk-cache key changes (a
# full rebuild instead of a relink), and the beta's Metal toolchain is a stub — every
# shader compile dies with "cannot execute tool 'metal' due to missing Metal Toolchain".
# `xcrun` itself ignores bazel's XCODE_VERSION_OVERRIDE and always runs the
# `xcode-select`ed Xcode, so the compiler was the release one all along — only bazel's
# idea of it was wrong.
#
# This writes an explicit `xcode_config` for the selected Xcode (the same shape as the
# `local_config_xcode` repository — generated by bazel itself up to 8.x, by apple_support's
# `xcode_configure` extension since the 13.0 bump to bazel 9, which has no native
# `xcode_config` / `xcode_version` rules any more, hence the explicit loads below) and an
# rc file that `.bazelrc` try-imports. The rc
# file also puts DEVELOPER_DIR into every action's environment: at execution time bazel
# turns XCODE_VERSION_OVERRIDE back into a developer dir with the same LaunchServices
# lookup (`XcodeLocalEnvProvider` → the embedded `xcode-locator`), which fails for a
# version LaunchServices will not report — but an action whose environment already
# carries DEVELOPER_DIR skips that lookup (bazel 8.4.2, `rewriteLocalEnv`). --action_env
# reaches only actions that take the default shell env; the one Apple action that did
# not, rules_apple's ObjcBinarySymbolStrip, is patched in the vendored copy
# (build-system/bazel-rules/rules_apple/apple/internal/compilation_support.bzl). Both files
# are gitignored and rewritten by every XTG build script, so an Xcode update is picked up
# on the next build, and a fresh checkout without them falls back to bazel's detection.
#
#   build-system/XTGXcodeConfig.sh        # writes build-system/XTGXcode/BUILD + XTGXcode.bazelrc

set -euo pipefail
cd "$(dirname "$0")/.."

OUT_DIR="build-system/XTGXcode"
OUT_RC="build-system/XTGXcode.bazelrc"

developer_dir="$(xcode-select -p)"
run() { env -i DEVELOPER_DIR="$developer_dir" PATH=/usr/bin:/bin "$@"; }

version_output="$(run xcodebuild -version)"
short="$(printf '%s\n' "$version_output" | sed -n 's/^Xcode //p' | head -1)"
build="$(printf '%s\n' "$version_output" | sed -n 's/^Build version //p' | head -1)"
if [ -z "$short" ] || [ -z "$build" ]; then
    echo "XTGXcodeConfig: cannot read 'xcodebuild -version' for $developer_dir" >&2
    exit 1
fi

# bazel spells a version major.minor.patch.build and aliases it every shorter way.
IFS=. read -r major minor patch <<< "$short"
expanded="${major}.${minor:-0}.${patch:-0}"
full="${expanded}.${build}"
name="version$(printf '%s' "$full" | tr . _)"
aliases=""
for alias in "$full" "$build" "$short" "$expanded" "$major"; do
    case ",$aliases," in *",'$alias',"*) continue ;; esac
    aliases="${aliases:+$aliases, }'$alias'"
done

sdk_version() { run xcrun --sdk "$1" --show-sdk-version 2>/dev/null || true; }

mkdir -p "$OUT_DIR"
{
    echo "# XTG: generated by build-system/XTGXcodeConfig.sh for $developer_dir — do not edit."
    echo "load('@build_bazel_apple_support//xcode:xcode_config.bzl', 'xcode_config')"
    echo "load('@build_bazel_apple_support//xcode:xcode_version.bzl', 'xcode_version')"
    echo
    echo "package(default_visibility = ['//visibility:public'])"
    echo
    echo "xcode_version("
    echo "    name = '$name',"
    echo "    version = '$full',"
    echo "    aliases = [$aliases],"
    for pair in ios:iphoneos tvos:appletvos macos:macosx visionos:xros watchos:watchos; do
        sdk="$(sdk_version "${pair##*:}")"
        [ -n "$sdk" ] && echo "    default_${pair%%:*}_sdk_version = '$sdk',"
    done
    echo ")"
    echo
    echo "xcode_config("
    echo "    name = 'host_xcodes',"
    echo "    versions = [':$name'],"
    echo "    default = ':$name',"
    echo ")"
} > "$OUT_DIR/BUILD"

{
    echo "# XTG: generated by build-system/XTGXcodeConfig.sh — do not edit."
    echo "build --xcode_version_config=//build-system/XTGXcode:host_xcodes"
    echo "build --action_env=DEVELOPER_DIR=$developer_dir"
} > "$OUT_RC"

echo "xcode      : $full ($developer_dir) -> $OUT_DIR/BUILD, $OUT_RC"
